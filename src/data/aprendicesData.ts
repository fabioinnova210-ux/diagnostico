const STORAGE_KEY_APRENDICES = 'sena_asistencia_admin_aprendices_v1';
const STORAGE_KEY_SESION = 'sena_sesion_activa_v1';

export function getAprendicesList(): Aprendiz[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEY_APRENDICES);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY_APRENDICES, JSON.stringify(APRENDICES_INICIALES));
      return APRENDICES_INICIALES;
    }
    return JSON.parse(raw);
  } catch (e) {
    console.error('Error cargando aprendices', e);
    return APRENDICES_INICIALES;
  }
}

export function saveAprendiz(aprendizActualizado: Aprendiz): Aprendiz[] {
  const list = getAprendicesList();
  const index = list.findIndex((a) => a.id === aprendizActualizado.id);
  let updated: Aprendiz[];
  if (index >= 0) {
    updated = [...list];
    updated[index] = aprendizActualizado;
  } else {
    updated = [...list, aprendizActualizado];
  }
  localStorage.setItem(STORAGE_KEY_APRENDICES, JSON.stringify(updated));
  return updated;
}

export function resetAprendicesToDefault(): Aprendiz[] {
  localStorage.setItem(STORAGE_KEY_APRENDICES, JSON.stringify(APRENDICES_INICIALES));
  return APRENDICES_INICIALES;
}

export function exportAprendicesToCSV(): string {
  const list = getAprendicesList();
  const headers = [
    'No.',
    'Tipo Documento',
    'Número Documento',
    'Nombres',
    'Apellidos',
    'Correo Electrónico',
    'Celular',
    'Ciudad',
    'Empresa Proyecto',
    'Estado Diagnóstico',
    'Puntaje (0-10)',
    'Porcentaje (%)',
    'Resultado',
    'Fecha Realización',
    'Retroalimentación Instructor',
  ];

  const rows = list.map((a, idx) => [
    idx + 1,
    a.tipoDocumento,
    `"${a.numeroDocumento}"`,
    `"${a.nombres}"`,
    `"${a.apellidos}"`,
    `"${a.correo}"`,
    `"${a.celular}"`,
    `"${a.ciudad}"`,
    `"${a.empresaProyecto || 'Sin asignar'}"`,
    a.haRealizadoDiagnostico ? 'Presentada' : 'Pendiente',
    a.puntajeDiagnostico !== undefined ? a.puntajeDiagnostico : 'N/A',
    a.porcentajeDiagnostico !== undefined ? `${a.porcentajeDiagnostico}%` : 'N/A',
    a.haRealizadoDiagnostico ? (a.aprobado ? 'APROBADO (>=70%)' : 'NO APROBADO (<70%)') : 'NO PRESENTÓ',
    a.fechaRealizacion || 'N/A',
    `"${(a.retroalimentacionInstructor || '').replace(/"/g, '""')}"`,
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}
